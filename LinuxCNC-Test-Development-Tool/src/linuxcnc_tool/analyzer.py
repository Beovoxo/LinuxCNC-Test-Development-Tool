"""System health checks and read-only real-time diagnostics."""
from __future__ import annotations
import platform
from pathlib import Path
from . import diagnostics as diag

def realtime_details() -> str:
    parts = [
        "===== REAL-TIME KERNEL =====",
        f"Kernel release: {platform.release()}",
        f"Kernel command line: {Path('/proc/cmdline').read_text().strip() if Path('/proc/cmdline').exists() else 'Not available'}",
        "",
        "===== LINUXCNC THREADS =====",
        diag.run_cmd(["halcmd", "show", "thread"], timeout=6),
        "",
        "===== INTERRUPTS (snapshot) =====",
        diag.run_cmd(["bash", "-lc", "head -n 35 /proc/interrupts"], timeout=4),
        "",
        "===== LATENCY MEASUREMENT =====",
        "No latency/jitter number is generated by this report. Start LinuxCNC latency-histogram or latency-test and record the measured maximum jitter under representative load.",
    ]
    return "\n".join(parts)

def hardware_inventory() -> str:
    return diag.hardware_info() + "\n\n===== NETWORK ADAPTERS =====\n" + diag.run_cmd(["bash", "-lc", "for n in /sys/class/net/*; do [ -e \"$n\" ] || continue; i=${n##*/}; echo \"--- $i ---\"; ethtool \"$i\" 2>/dev/null | grep -E 'Speed:|Duplex:|Link detected:' || true; done"], timeout=10)

def health_report() -> str:
    checks = []
    info = diag.system_info()
    checks.append(("LinuxCNC command", "AVAILABLE" if "Not available" not in info.get("LinuxCNC","") and "not found" not in info.get("LinuxCNC","").lower() else "CHECK"))
    checks.append(("HAL utility", "AVAILABLE" if "Not installed" not in info.get("HAL utility","") else "NOT AVAILABLE"))
    checks.append(("EtherCAT utility", "AVAILABLE" if "Not installed" not in info.get("EtherCAT utility","") else "NOT CONFIGURED / NOT AVAILABLE"))
    checks.append(("Network tools", "AVAILABLE" if diag.run_cmd(["ip","-brief","link"]) != "Not available: ip" else "NOT AVAILABLE"))
    rt = platform.release()
    checks.append(("RT kernel", "POSSIBLE RT KERNEL – VERIFY" if ("-rt" in rt or "PREEMPT_RT" in rt) else "NOT CONFIRMED"))
    lines = ["SYSTEM HEALTH CHECK", "===================", ""]
    for name, status in checks:
        lines.append(f"{status:28} {name}")
    lines += ["", "Notes:", "- Checks are capability/availability checks, not a safety certification.",
              "- EtherCAT status requires a configured master and suitable permissions.",
              "- RT kernel detection from the version string is only indicative.",
              "- Actual latency/jitter must be measured with LinuxCNC tools."]
    return "\n".join(lines)
